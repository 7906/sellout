/** 第 day 天的早间公司邮件（确定生成，重启不变） */
export function morningEmail(day: number): CompanyEmail {
  return EMAILS[(day - 1) % EMAILS.length]!;
}

/** 第 day 天的街区新闻（步进与邮件数互质，避免天天成对出现） */
export function eveningNews(day: number): string {
  return NEWS[((day - 1) * 5 + 2) % NEWS.length]!;
}
